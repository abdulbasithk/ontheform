BEGIN;

ALTER TABLE forms
  ADD COLUMN IF NOT EXISTS access_code_required BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS access_code_single_use BOOLEAN NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS form_access_codes (
  form_id UUID NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  code_hash VARCHAR(64) NOT NULL,
  used_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (form_id, code_hash)
);

COMMIT;